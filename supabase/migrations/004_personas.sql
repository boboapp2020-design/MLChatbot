1. ระบุว่าคำถามอยู่หมวดไหนใน 4 หมวดข้างต้น เปิดไฟล์อ้างอิงที่ตรง
2. ดึงตาราง/ขั้นตอนที่เกี่ยวข้องมาสรุปตรงประเด็น — ไม่ต้องยกทั้งไฟล์
