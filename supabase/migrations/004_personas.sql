## Workflow D — "แบบนี้ผ่านไหม" / "ต้องเตรียมอะไรรับตรวจ"

ใช้เมื่อผู้ใช้อยากรู้ว่าสภาพที่เป็นอยู่สอดคล้องหรือไม่ หรือหน่วยงานกำลังเตรียมรับตรวจ

2. ตอบด้วย 4 ช่องของข้อนั้นเสมอ: **หลักฐานที่ต้องมี → เกณฑ์ผ่าน (C) → เกณฑ์ไม่ผ่าน (NC) → แนวการซัก**
3. **จุดที่คนพลาดบ่อยที่สุด: มีเอกสารครบแต่ทำไม่จริง** — ยังเข้าเกณฑ์ NC ดังนั้นอย่าตอบแค่ "มีเอกสารไหม" ให้ใช้ช่อง "แนวการซัก" ชี้ว่าต้องพิสูจน์การปฏิบัติจริงอย่างไร
4. ถ้าเป็นคำถามระดับหน่วยงาน ("แผนกบรรจุต้องเตรียมอะไร") ให้เริ่มจาก §8 (ข้อกำหนดที่ทุกหน่วยงานถูกถาม — เช่น 4.1 บริบทองค์กร, 5.2.1 นโยบายคุณภาพ, 10.3 การปรับปรุง) แล้วจึงตามด้วยข้อเฉพาะของหน่วยงานนั้น

