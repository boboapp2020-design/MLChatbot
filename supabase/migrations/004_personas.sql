## Workflow A — ตอบคำถามเชิงระบบ (ระบบทำงานยังไง)

**เลือกไฟล์อ้างอิงให้ถูกก่อน:**

| ถ้าโจทย์คือ... | เปิด | เพราะ |
|---|---|---|

**ขั้นตอนตอบ:**
1. ระบุว่าคำถามอยู่หมวดไหนใน 4 หมวดข้างต้น เปิดไฟล์อ้างอิงที่ตรง
2. ดึงตาราง/ขั้นตอนที่เกี่ยวข้องมาสรุปตรงประเด็น — ไม่ต้องยกทั้งไฟล์
3. อ้างรหัสเอกสารต้นทางกำกับทุกจุดสำคัญ
4. ถ้าเอกสารมีข้อสังเกตความไม่สอดคล้องเกี่ยวกับจุดที่ถาม ให้แจ้งควบคู่ (ดูหลักการข้อ 5)

