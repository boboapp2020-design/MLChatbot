**1 OPRP:** ตะแกรง (60 mesh) + ผ้ากรอง

**Zoning EMP:** Zone 1 (สัมผัสตรง, 10–20%) → Zone 2 (ใกล้เคียง, 40–50%) → Zone 3 (ในพื้นที่, 30–40%) → Zone 4 (นอกพื้นที่ผลิต, 10%)

**สถานะการรับรอง ณ ปี 2026 (จากรายงาน LRQA):**
- FSSC 22000 v6 + GHP/HACCP Codex 2022 — ตรวจ 25–28 ม.ค. 2026, ผลแนะนำ **ต่ออายุการรับรอง** / ISO 9001:2015 — ตรวจทางไกล 24–26 มี.ค. 2026, **ต่ออายุ**
