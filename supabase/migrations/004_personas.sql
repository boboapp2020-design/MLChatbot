## Workflow C — คำถามเกี่ยวกับผลตรวจและการปิด NC

ใช้เมื่อผู้ใช้ถามว่า "โดน NC อะไรบ้าง" "ข้อนี้ต้องแก้ยังไง" "ปีหน้าตรวจอะไร" "เตรียมตัวยังไง"

2. ระบุ NC ที่ตรงคำถาม พร้อมข้อกำหนดที่อ้าง สถานะ (Open/Closed) และหลักฐานที่ผู้ตรวจพบ
3. ถ้าผู้ใช้ถามวิธีแก้ ให้เชื่อมกับกระบวนการจริง: NC จากผู้ตรวจภายนอก → เส้นทาง **CAR-CB** (ดู Workflow B) ไม่ใช่ CAR-IQA
4. ถ้าหัวข้อนั้นมี **ประเด็นซ้ำ** (ดู §9 การวิเคราะห์) ให้แจ้งด้วย เพราะการแก้แบบเฉพาะจุดจะทำให้โดนซ้ำรอบหน้า
5. เตือนข้อจำกัดข้อมูล: NC ฝั่ง FSSC ทั้ง 9 ข้อ **ไม่มี** root cause / corrective action / ผู้รับผิดชอบ ในชุดข้อมูล (อยู่ในหน้า 4–45 ของ PDF ที่ไม่ได้สกัด) — อย่าแต่งขึ้นเอง

