## ความรู้หลักที่ต้องอยู่ในคำตอบเสมอ (ไม่ต้องเปิดไฟล์ก็ตอบได้)

**CCP ทั้ง 6 จุด (จาก ML-SP-1600-011/012):**
| CCP | จุดควบคุม | ค่าวิกฤต |
|---|---|---|
| CCP 1B | A-Massecuite vacuum pan (เฉพาะ DCR) | อุณหภูมิ > 63°C ต่อเนื่อง > 45 นาที |
| CCP 1.1P | แม่เหล็ก No.1 ก่อนตะแกรงคัดเม็ด (เฉพาะ DCR) | ไม่พบเศษโลหะ > 3mm/5kg, ความแรง > 9,000 Gauss |
| CCP 1.2P / 2P / 3P / 4P | Metal Detector (ไลน์ 25/50 kg และ 1,000 kg) | Fe ≥ 2.5mm / non-Fe ≥ 3mm / SUS ≥ 3mm |

**1 OPRP:** ตะแกรง (60 mesh) + ผ้ากรอง

**Zoning EMP:** Zone 1 (สัมผัสตรง, 10–20%) → Zone 2 (ใกล้เคียง, 40–50%) → Zone 3 (ในพื้นที่, 30–40%) → Zone 4 (นอกพื้นที่ผลิต, 10%)

**สถานะการรับรอง ณ ปี 2026 (จากรายงาน LRQA):**
- FSSC 22000 v6 + GHP/HACCP Codex 2022 — ตรวจ 25–28 ม.ค. 2026, ผลแนะนำ **ต่ออายุการรับรอง** / ISO 9001:2015 — ตรวจทางไกล 24–26 มี.ค. 2026, **ต่ออายุ**
- **ไม่มี Major NC** ทั้งสองรอบ — มี Minor NC ใหม่ 12 ข้อ (FSSC 9, GHP 1, HACCP 1, ISO 9001 1) และปิด NC รอบก่อน 19 ข้อ
- หัวข้อที่ยังเปิดค้าง: hygienic design, hazard-control equipment, traceability/lot ID, flow diagram, calibration, ฉลากออร์แกนิก, change control, shelf-life, food safety culture, การตอบสนองค่าที่ออกนอกสเปก
- ตรวจครั้งถัดไป: **Surveillance 1 — กุมภาพันธ์ 2027**

**Matrix ความเสี่ยง 4 ชุด — อย่าสลับ:**
- TACCP: Likelihood×Severity 4×4 → H/M/L/SA
- VACCP: O+D สเกล 0–10 → SA(0-2)/L(3-5)/M(6-8)/H(9-10)
- QMS Risk ทั่วไป: Likelihood×Impact 5×5 → Critical(13-25)/High(7-12)/Medium(3-6)/Low(1-2)

