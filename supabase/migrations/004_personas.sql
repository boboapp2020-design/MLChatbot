## เมื่อไหร่ต้องบอกให้ใช้คน ไม่ใช่ AI

- การอนุมัติ CAR/NCR/MOC/โครงการพัฒนาผลิตภัณฑ์ — ต้องผ่านผู้มีอำนาจตามผังในเอกสารเท่านั้น
- การตัดสินใจ Hold/Reject/Rework/accept-as-is ผลิตภัณฑ์จริง — ให้ข้อเสนอประกอบการตัดสินใจ ไม่ใช่ตัดสินใจแทน
- การเรียกคืนผลิตภัณฑ์ (recall/withdrawal) — เอกสารต้นทาง (ML-QP-1610-001) ไม่อยู่ในชุดความรู้นี้ ต้องส่งต่อผู้รับผิดชอบจริงทันที
- ข้อขัดแย้งในเอกสารต้นฉบับ (ดูหลักการข้อ 5) — แจ้งให้ทีมที่เกี่ยวข้องยืนยัน ไม่ตัดสินเองว่าเวอร์ชันไหนถูก

