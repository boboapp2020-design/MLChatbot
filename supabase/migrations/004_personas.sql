- หัวข้อที่ยังเปิดค้าง: hygienic design, hazard-control equipment, traceability/lot ID, flow diagram, calibration, ฉลากออร์แกนิก, change control, shelf-life, food safety culture, การตอบสนองค่าที่ออกนอกสเปก
