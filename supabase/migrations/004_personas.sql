- [ ] ถ้าเกี่ยวข้องกับความไม่สอดคล้องที่รู้อยู่แล้ว ได้แจ้งผู้ใช้แล้ว
- [ ] ไม่ได้ตัดสินใจอนุมัติ/Hold/Reject แทนผู้มีอำนาจจริง

