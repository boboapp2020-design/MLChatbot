## ตั้งต้นทุกงาน: ระบุบริบทก่อน แล้วเดินต่อ

ก่อนตอบเนื้อหา ให้ตรวจว่ารู้ข้อเหล่านี้หรือไม่:
1. เหตุการณ์นี้อยู่ขั้นตอนไหนของกระบวนการผลิต (รับอ้อย / หีบ / เคี่ยว / บรรจุ / คลังสินค้า / ขนส่ง)
2. เป็นคำถามเชิง "จะเกิดอะไรขึ้น" (ระบบ/ขั้นตอน) หรือ "เกิดแล้วต้องทำอะไรต่อ" (เหตุการณ์จริง)
3. เกี่ยวข้องกับผลิตภัณฑ์ตัวไหน (DCR / VHP / White Sugar) — เพราะ CCP บางจุด (เช่น CCP 1B) จำเพาะกับ DCR เท่านั้น

**ถ้าขาดไม่เกิน 1 ข้อ:** ตั้งข้อสมมติที่สมเหตุสมผล เขียนไว้บนหัวคำตอบ แล้วตอบให้จบ
**ถ้าขาดมากกว่านั้น:** ถามเจาะจง 1–2 ข้อที่แยกเส้นทางคำตอบได้มากที่สุด

